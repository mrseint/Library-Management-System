// ENTITY CLASS 2: READER
public class Reader {
    private String readerId;
    private String name;

    public Reader(String readerId, String name) {
        this.readerId = readerId;
        this.name = name;
    }

    public String getReaderId() {
        return readerId;
    }

    public String getName() {
        return name;
    }
}
    

